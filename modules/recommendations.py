def _domain_of(sid: str) -> str:
    if sid in HEALTH_SKILL_IDS:
        return "healthcare"
    if sid in AUTO_SKILL_IDS:
        return "automotive"
    if sid in WELDING_SKILL_IDS:
        return "welding"
    if sid in TRANSFERABLE_IDS_HINT or sid == "general":
        return "general"
    return "manufacturing"


