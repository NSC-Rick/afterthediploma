# Trigger that is always considered "not present" (forces inclusion of the
# partnership recommendation which cannot be detected from text alone).
ALWAYS_GAP = {"work-based learning placeholder"}


def generate_recommendations(
    skills_df: pd.DataFrame, careers: pd.DataFrame, employers: pd.DataFrame
) -> pd.DataFrame:
    presence = skill_presence(skills_df)

    # How many pathway rows list a skill as required? -> "pathways strengthened"
    skill_demand: dict[str, list[str]] = {}
    for _, occ in careers.iterrows():
        for sid in str(occ.get("required_skills_ids", "")).split(";"):
            sid = sid.strip()
            if sid:
                skill_demand.setdefault(sid, []).append(occ["title"])

    n_employers = len(employers)
    present_ids = set(
        skills_df.loc[
            skills_df["status"].isin([STATUS_DOCUMENTED, STATUS_INFERRED]),
            "skill_id",
        ]
    )
    rows = []
    for entry in CATALOG:
        triggers = entry["trigger_skills"]
        # Domain gate: an entry applies only when its trigger domains are
        # detected in the curriculum's present skills (prevents welding
        # recs on LNA/Auto profiles and vice-versa; generalizes to new
        # domains via _domain_of).
        entry_domains = {_domain_of(t) for t in triggers} - {"general"}
        detected = {_domain_of(s) for s in present_ids} - {"general"}
        if entry_domains and detected and not entry_domains <= detected:
            continue
        fires = any(
            (t in ALWAYS_GAP) or presence.get(t) not in (STATUS_DOCUMENTED, STATUS_INFERRED)
            for t in triggers
        )
        # also fire when every trigger is only inferred (weaker gap)
        weak_fire = all(
            presence.get(t) == STATUS_INFERRED for t in triggers if t in presence
        ) and triggers and all(t in presence for t in triggers)
        if not (fires or weak_fire):
            continue
        unlocked = sorted({t for s in triggers for t in skill_demand.get(s, [])})
        rows.append(
            {
                "recommendation": entry["title"],
                "gap_addressed": entry["gap"],
                "effort": entry["effort"],
                "group": GROUP_LABELS[entry["effort"]],
                "pathways_strengthened": "; ".join(unlocked) if unlocked else "Broadens optionality",
                "n_pathways": len(unlocked),
                "employer_demand_evidence": (
                    f"{n_employers} employers in the regional dataset; see employer "
                    "skill tags for sector-level alignment."
                ),
                "student_benefit": entry["benefit"],
                "rationale": entry["rationale"],
                "connection": entry.get(
                    "connection", "Builds on documented curriculum content"
                ),
                "validation": entry.get(
                    "validation", "Validate employer demand before committing resources"
                ),
                "confidence_limitations": entry["confidence"],
                "data_status": "Derived analysis - advisory recommendation",
            }
        )
    df = pd.DataFrame(rows)
    if df.empty:
        return df
    df["_e"] = df["effort"].map(EFFORT_ORDER)
    return (
        df.sort_values(["_e", "n_pathways"], ascending=[True, False])
        .drop(columns="_e")
        .reset_index(drop=True)
    )


def careers_with_skill_ids(careers: pd.DataFrame, occupations: pd.DataFrame) -> pd.DataFrame:
    """Join raw required-skill ids onto the scored careers table."""
    m = occupations.set_index(["soc_code", "title"])["required_skills"]
    out = careers.copy()
    out["required_skills_ids"] = out.apply(
        lambda r: m.get((r["soc_code"], r["title"]), ""), axis=1
    )
    return out
